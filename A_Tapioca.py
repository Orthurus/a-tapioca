def _pasta_dados():
    base = os.environ.get("APPDATA") or os.path.join(os.path.expanduser("~"), ".local", "share")
    return os.path.join(base, "ATapioca")


DATA_DIR = _pasta_dados()


def _pasta_app():
    return os.path.dirname(os.path.abspath(sys.executable if getattr(sys, "frozen", False) else __file__))


def migrar_dados_antigos():
    """Copia (sem apagar) cardapio/vendas/config da pasta antiga (ao lado do programa)
    para DATA_DIR, na primeira execução."""
    os.makedirs(DATA_DIR, exist_ok=True)
    for nome in ("cardapio.json", "vendas.json", "config.json"):
        destino = os.path.join(DATA_DIR, nome)
        if os.path.exists(destino):
            continue
        for pasta in dict.fromkeys((os.getcwd(), _pasta_app())):
            origem = os.path.join(pasta, nome)
            if os.path.isfile(origem):
                try:
                    shutil.copy2(origem, destino)
                except OSError:
                    pass
                break


def _json_valido(caminho):
    try:
        with open(caminho, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def salvar_json_atomico(caminho, dados):
    """Grava em .tmp, valida, guarda o arquivo bom anterior como .bak e troca com os.replace.
    Levanta exceção se algo falhar (o arquivo original fica intacto)."""
    os.makedirs(os.path.dirname(caminho), exist_ok=True)
    tmp = caminho + ".tmp"
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(dados, f, ensure_ascii=False, indent=4)
            f.flush()
            os.fsync(f.fileno())
        with open(tmp, "r", encoding="utf-8") as f:  # relê para garantir que o JSON gravado é válido
            json.load(f)
        # só vira backup se o atual estiver íntegro (nunca sobrescreve um .bak bom com lixo)
        if os.path.exists(caminho) and _json_valido(caminho) is not None:
            try:
                shutil.copy2(caminho, caminho + ".bak")
            except OSError:
                pass
        os.replace(tmp, caminho)
    except Exception:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise


def carregar_json_seguro(caminho, padrao):
    """Devolve (dados, aviso). Se o arquivo estiver corrompido, preserva uma cópia
    (.corrompido-DATA), tenta o .bak e só então cai no padrão — e AVISA, em vez de
    sobrescrever tudo em silêncio."""
    bak = caminho + ".bak"
    if not os.path.exists(caminho) and not os.path.exists(bak):
        return padrao, None

    def ok(d):
        return d is not None and isinstance(d, type(padrao))

    if os.path.exists(caminho):
        dados = _json_valido(caminho)
        if ok(dados):
            return dados, None
        try:  # guarda o arquivo ruim para análise/recuperação manual
            shutil.copy2(caminho, f"{caminho}.corrompido-{datetime.now():%Y%m%d_%H%M%S}")
        except OSError:
            pass
    dados = _json_valido(bak) if os.path.exists(bak) else None
    nome = os.path.basename(caminho)
    if ok(dados):
        return dados, f"O arquivo {nome} estava danificado e foi restaurado da cópia de segurança (.bak). Os últimos lançamentos podem não estar presentes."
    return padrao, (f"O arquivo {nome} estava danificado e não havia cópia de segurança utilizável. "
                    f"Uma cópia do arquivo ruim foi guardada em:\n{DATA_DIR}")

