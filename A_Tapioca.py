    def on_report_date_change(self):
        self.selected_report_date = self.date_entry.get_date()
        self.generate_report()

    def shift_report_date(self, delta_dias):
        from datetime import timedelta
        self.selected_report_date += timedelta(days=delta_dias)
        self.lbl_report_date.config(text=self.selected_report_date.strftime("%d/%m/%Y"))
        self.generate_report()

    def reset_report_date_today(self):
        self.selected_report_date = datetime.now().date()
        if TKCALENDAR_OK:
            self.date_entry.set_date(self.selected_report_date)
        else:
            self.lbl_report_date.config(text=self.selected_report_date.strftime("%d/%m/%Y"))
        self.generate_report()

    def generate_report(self):
        self.tree_resumo.delete(*self.tree_resumo.get_children())
        self.tree_hist.delete(*self.tree_hist.get_children())

        data_str = self.selected_report_date.strftime("%d/%m/%Y")
        eh_hoje = self.selected_report_date == datetime.now().date()
        self.lbl_relatorio_titulo.config(
            text=f"Relatório de Vendas — {'Hoje' if eh_hoje else data_str}"
        )

        vendas_dia = [v for v in self.vendas if v.get("data") == data_str]

        total_faturado = 0.0
        itens_vendidos = {}

        for v in vendas_dia:
            total_faturado += v.get("total", 0)
            for item, qtd in v.get("itens", {}).items():
                itens_vendidos[item] = itens_vendidos.get(item, 0) + qtd

        for item, qtd in sorted(itens_vendidos.items(), key=lambda x: x[1], reverse=True):
            self.tree_resumo.insert("", tk.END, text=item, values=(qtd,))

        for i, v in enumerate(vendas_dia, 1):
            self.tree_hist.insert("", tk.END, text=f"#{i}",
                                   values=(v.get("hora", ""), f"R$ {v.get('total', 0):.2f}"))

        if not vendas_dia:
            self.tree_resumo.insert("", tk.END, text="Nenhuma venda registrada nesta data", values=("",))

        rotulo_total = "Faturamento Hoje" if eh_hoje else f"Faturamento em {data_str}"
        self.lbl_report_total.config(
            text=f"{rotulo_total}: R$ {total_faturado:.2f}".replace(".", ",")
        )


