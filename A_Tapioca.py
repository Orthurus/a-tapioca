    def update_estoque_tree(self):
        self.tree_estoque.delete(*self.tree_estoque.get_children())
        for nome, info in sorted(self.menu.items(), key=lambda x: (x[1]["categoria"], x[0])):
            self.tree_estoque.insert("", tk.END, iid=nome, text=nome,
                                      values=(info["categoria"], f"R$ {info['preco']:.2f}"))

    def on_select_estoque(self, event):
        pass  # seleção apenas habilita os botões; edição real via load_selected_for_edit

    def load_selected_for_edit(self):
        sel = self.tree_estoque.selection()
        if not sel:
            messagebox.showinfo("Selecione um produto", "Clique em um produto da lista para editar.")
            return
        nome = sel[0]
        info = self.menu[nome]

        self.editing_product = nome
        self.entry_name.delete(0, tk.END)
        self.entry_name.insert(0, nome)
        self.entry_price.delete(0, tk.END)
        self.entry_price.insert(0, f"{info['preco']:.2f}")
        self.combo_categoria.set(info["categoria"])

        self.lbl_form_title.config(text="Editando Produto")
        self.btn_save_product.config(text="Atualizar Produto")
        self.btn_cancel_edit.pack(fill=tk.X, padx=18, pady=(0, 18))

    def cancel_edit(self):
        self.editing_product = None
        self.entry_name.delete(0, tk.END)
        self.entry_price.delete(0, tk.END)
        self.combo_categoria.current(0)
        self.lbl_form_title.config(text="Novo Produto")
        self.btn_save_product.config(text="Salvar Produto")
        self.btn_cancel_edit.pack_forget()

    def save_product(self):
        nome = self.entry_name.get().strip()
        price_str = self.entry_price.get().strip().replace(",", ".")
        categoria = self.combo_categoria.get() or "Outros"

        if not nome or not price_str:
            messagebox.showwarning("Aviso", "Preencha o nome e o preço do produto.")
            return
        try:
            preco = float(price_str)
            if preco < 0:
                raise ValueError
        except ValueError:
            messagebox.showerror("Erro", "Digite um valor numérico válido para o preço.")
            return

        # Se está editando e o nome mudou, remove o registro antigo
        if self.editing_product and self.editing_product != nome:
            if nome in self.menu:
                messagebox.showerror("Erro", "Já existe um produto com esse nome.")
                return
            del self.menu[self.editing_product]
        elif not self.editing_product and nome in self.menu:
            if not messagebox.askyesno("Produto existente",
                                        f"'{nome}' já existe. Deseja sobrescrever?"):
                return

        self.menu[nome] = {"preco": preco, "categoria": categoria}
        self.save_data(self.menu_file, self.menu)

        was_editing = self.editing_product is not None
        self.cancel_edit()
        self.update_estoque_tree()
        if self.active_nav == "pedido":
            self.update_menu_tree()

        messagebox.showinfo("Sucesso",
                             f"'{nome}' {'atualizado' if was_editing else 'salvo'} no cardápio!")

    def delete_product(self):
        sel = self.tree_estoque.selection()
        if not sel:
            messagebox.showinfo("Selecione um produto", "Clique em um produto da lista para excluir.")
            return
        nome = sel[0]
        if messagebox.askyesno("Confirmar exclusão", f"Remover '{nome}' do cardápio?"):
            del self.menu[nome]
            self.save_data(self.menu_file, self.menu)
            self.cart.pop(nome, None)
            if self.editing_product == nome:
                self.cancel_edit()
            self.update_estoque_tree()
            if self.active_nav == "pedido":
                self.update_menu_tree()
                self.update_cart_tree()

