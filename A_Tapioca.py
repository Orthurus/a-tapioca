    def _path(self, filename):
        return os.path.join(DATA_DIR, filename)

    def load_data(self, filename, default_data):
        dados, aviso = carregar_json_seguro(self._path(filename), default_data)
        if aviso:
            self._avisos_carga.append(aviso)
        return dados

    def save_data(self, filename, data, silencioso=False):
        """Grava de forma atômica. Devolve True/False; em falha avisa o usuário
        (a menos que silencioso=True) e o arquivo anterior continua intacto."""
        try:
            salvar_json_atomico(self._path(filename), data)
            return True
        except Exception as e:
            if not silencioso:
                messagebox.showerror("Erro ao salvar",
                                     f"Não foi possível salvar {filename}:\n{e}\n\nOs dados anteriores foram preservados.")
            return False

    def mostrar_avisos_carga(self):
        avisos, self._avisos_carga = self._avisos_carga, []
        for a in avisos:
            messagebox.showwarning("Dados recuperados", a)

    # ----- pedidos abertos (mesas/comandas) -----
    def load_orders(self):
        dados = self.load_data(self.pedidos_file, {})
        orders = {}
        for mesa, itens in (dados.get("orders") or {}).items():
            if not isinstance(itens, dict):
                continue
            limpo = {}
            for nome, qtd in itens.items():
                if nome in self.menu and isinstance(qtd, int) and qtd > 0:
                    limpo[nome] = qtd
            orders[str(mesa)] = limpo
        if not orders:
            return
        self.orders = orders
        atual = dados.get("current")
        self.current_table = atual if atual in orders else next(iter(orders))
        nums = [int(m.split()[-1]) for m in orders if m.startswith("Mesa ") and m.split()[-1].isdigit()]
        self._next_table_num = max([2, dados.get("next", 2) if isinstance(dados.get("next"), int) else 2] + [n + 1 for n in nums])

    def save_orders(self):
        ok = self.save_data(self.pedidos_file, {
            "orders": self.orders, "current": self.current_table, "next": self._next_table_num,
        }, silencioso=True)
        if not ok and not self._aviso_pedidos_dado:
            self._aviso_pedidos_dado = True
            messagebox.showwarning("Aviso", "Não foi possível salvar os pedidos abertos em disco.\n"
                                   "Eles continuam na tela, mas seriam perdidos se o programa fechar.")

    @property
    def cart(self):
        """Carrinho da mesa/comanda atualmente selecionada.

        Mantido como propriedade para que todo o restante do código
        (que já usava self.cart) continue funcionando sem alterações,
        agora apontando sempre para o pedido da mesa ativa.
        """
        return self.orders[self.current_table]

    def migrate_menu(self):
        """Converte cardápios antigos (nome -> preço) para o novo formato
        (nome -> {'preco':..., 'categoria':...}) sem perder dados."""
        changed = False
        for nome, valor in list(self.menu.items()):
            if isinstance(valor, (int, float)):
                self.menu[nome] = {"preco": float(valor), "categoria": "Outros"}
                changed = True
        if changed:
            self.save_data(self.menu_file, self.menu)

