    def update_menu_tree(self, filtro=""):
        self.tree_menu.delete(*self.tree_menu.get_children())
        filtro = filtro.strip().lower()
        for nome, info in sorted(self.menu.items(), key=lambda x: (x[1]["categoria"], x[0])):
            if filtro and filtro not in nome.lower():
                continue
            preco = info["preco"]
            self.tree_menu.insert("", tk.END, iid=nome, text=nome,
                                   values=(info["categoria"], f"R$ {preco:.2f}"))

    # ------------------------------------------------------------
    # MESAS / COMANDAS — permite manter vários pedidos abertos ao
    # mesmo tempo, um por cliente/mesa, sem precisar finalizar um
    # antes de começar outro.
    # ------------------------------------------------------------
    def update_tables_bar(self):
        for w in self.tables_frame.winfo_children():
            w.destroy()
        self.table_tab_widgets = {}

        for nome in self.orders:
            qtd_itens = sum(self.orders[nome].values())
            texto = f"{nome} ({qtd_itens})" if qtd_itens else nome
            ativa = (nome == self.current_table)

            tab = tk.Label(self.tables_frame, text=texto, font=self.font_bold,
                            bg=GOLD if ativa else CREAM,
                            fg=MAROON_DARK if ativa else TEXT_DARK,
                            padx=14, pady=8, cursor="hand2")
            tab.pack(side=tk.LEFT, padx=4)
            tab.bind("<Button-1>", lambda e, n=nome: self.switch_table(n))
            tab.bind("<Button-3>", lambda e, n=nome: self.close_table(n))
            self.table_tab_widgets[nome] = tab

    def switch_table(self, nome):
        if nome not in self.orders or nome == self.current_table:
            if nome in self.orders:
                self.update_cart_tree()
            return
        self.current_table = nome
        self.update_tables_bar()
        self.update_cart_tree()

    def add_new_table(self):
        sugestao = f"Mesa {self._next_table_num}"
        nome = simpledialog.askstring(
            "Nova Mesa/Comanda",
            "Nome da mesa ou comanda:",
            initialvalue=sugestao,
            parent=self.root,
        )
        if nome is None:
            return
        nome = nome.strip()
        if not nome:
            return
        if nome in self.orders:
            messagebox.showwarning("Aviso", f"Já existe um pedido aberto para '{nome}'.")
            self.switch_table(nome)
            return

        self.orders[nome] = {}
        if nome == sugestao:
            self._next_table_num += 1
        self.current_table = nome
        self.update_tables_bar()
        self.update_cart_tree()

    def close_table(self, nome):
        """Fecha uma mesa/comanda SEM gerar venda (ex: cliente desistiu)."""
        if nome not in self.orders:
            return
        if self.orders[nome]:
            if not messagebox.askyesno(
                "Fechar mesa",
                f"'{nome}' ainda tem itens não finalizados.\n"
                "Deseja fechar mesmo assim, sem gerar venda?"
            ):
                return

        del self.orders[nome]
        if not self.orders:
            self.orders["Mesa 1"] = {}
            self.current_table = "Mesa 1"
            self._next_table_num = max(self._next_table_num, 2)
        elif self.current_table == nome:
            self.current_table = next(iter(self.orders))

        self.update_tables_bar()
        self.update_cart_tree()

    def add_to_cart(self):
        sel = self.tree_menu.selection()
        if not sel:
            messagebox.showinfo("Selecione um produto", "Clique em um produto da lista antes de adicionar.")
            return
        nome = sel[0]
        self.cart[nome] = self.cart.get(nome, 0) + 1
        self.update_cart_tree()

    def update_cart_tree(self):
        self.tree_cart.delete(*self.tree_cart.get_children())
        total = 0.0
        for nome, qtd in self.cart.items():
            preco = self.menu[nome]["preco"]
            subtotal = preco * qtd
            total += subtotal
            self.tree_cart.insert("", tk.END, iid=nome, text=nome,
                                   values=(qtd, f"R$ {subtotal:.2f}"))
        self.lbl_total.config(text=f"TOTAL: R$ {total:.2f}".replace(".", ","))
        self.save_orders()

    def increase_qty(self):
        sel = self.tree_cart.selection()
        if not sel:
            return
        nome = sel[0]
        self.cart[nome] += 1
        self.update_cart_tree()
        self.tree_cart.selection_set(nome)

    def decrease_qty(self):
        sel = self.tree_cart.selection()
        if not sel:
            return
        nome = sel[0]
        self.cart[nome] -= 1
        if self.cart[nome] <= 0:
            del self.cart[nome]
        self.update_cart_tree()
        if nome in self.cart:
            self.tree_cart.selection_set(nome)

    def remove_from_cart(self):
        sel = self.tree_cart.selection()
        if not sel:
            return
        nome = sel[0]
        del self.cart[nome]
        self.update_cart_tree()

    def clear_cart(self):
        if self.cart and not messagebox.askyesno(
                "Limpar pedido", f"Remover todos os itens de '{self.current_table}'?"):
            return
        self.cart.clear()
        self.update_cart_tree()

    def checkout(self):
        if not self.cart:
            messagebox.showwarning("Aviso", "O pedido está vazio.")
            return

        now = datetime.now()
        date_str = now.strftime("%d/%m/%Y")
        time_str = now.strftime("%H:%M:%S")

        # Cada linha guarda o preço PRATICADO agora; mudar o cardápio depois não altera o histórico.
        linhas = [{"nome": nome, "qtd": qtd,
                   "preco_unit": round(self.menu[nome]["preco"], 2),
                   "subtotal": round(self.menu[nome]["preco"] * qtd, 2)}
                  for nome, qtd in self.cart.items()]
        total_pedido = round(sum(l["subtotal"] for l in linhas), 2)
        venda_record = {
            "id": f"{now:%Y%m%d%H%M%S}-{uuid.uuid4().hex[:6]}",
            "data": date_str,
            "hora": time_str,
            "mesa": self.current_table,
            "itens": self.cart.copy(),   # nome -> qtd (mantido: o relatório e versões antigas leem isto)
            "linhas": linhas,            # detalhe com preço unitário da época
            "total": total_pedido,
        }
        self.vendas.append(venda_record)
        if not self.save_data(self.vendas_file, self.vendas, silencioso=True):
            self.vendas.pop()
            messagebox.showerror("Venda NÃO registrada",
                                 "Não foi possível gravar a venda em disco.\n"
                                 "O pedido foi mantido aberto. Verifique o disco/permissões e tente de novo.")
            return

        cupons_dir = os.path.join(DATA_DIR, "cupons")
        filename = os.path.join(cupons_dir, f"Cupom_{now.strftime('%d%m%Y_%H%M%S')}.txt")
        receipt_text = self.build_receipt_text(date_str, time_str, total_pedido)

        # A venda JÁ está gravada: falha no cupom não pode manter a mesa aberta
        # (senão o mesmo pedido seria finalizado duas vezes).
        erro_cupom = None
        try:
            os.makedirs(cupons_dir, exist_ok=True)
            with open(filename, "w", encoding="utf-8") as f:
                f.write(receipt_text)
        except Exception as e:
            erro_cupom = str(e)

        # A venda foi registrada: encerra esta mesa/comanda (ela some da
        # barra de mesas) sem afetar os pedidos abertos de outras mesas.
        mesa_finalizada = self.current_table
        del self.orders[mesa_finalizada]
        if not self.orders:
            self.orders["Mesa 1"] = {}
            self.current_table = "Mesa 1"
            self._next_table_num = max(self._next_table_num, 2)
        else:
            self.current_table = next(iter(self.orders))
        self.update_tables_bar()
        self.update_cart_tree()

        if self.active_nav == "relatorio":
            self.generate_report()

        if erro_cupom:
            messagebox.showwarning("Venda registrada", f"Venda registrada, mas não foi possível gerar o cupom:\n{erro_cupom}")
            return

        if not self.var_imprimir.get():
            messagebox.showinfo("Venda Finalizada", "Venda registrada (cupom não impresso).")
            return

        sucesso, erro = self.print_receipt(filename)
        if sucesso:
            messagebox.showinfo("Venda Finalizada", "Venda registrada e enviada para impressão!")
        else:
            messagebox.showwarning(
                "Impressão",
                "Venda registrada, mas não foi possível enviar para a impressora "
                f"automaticamente.\n\nDetalhe: {erro}\n\n"
                f"O cupom foi salvo em:\n{filename}\n"
                "Você pode abri-lo e imprimir manualmente."
            )

