    def _center(self, texto):
        """Centraliza o texto; se ultrapassar a largura do cupom, quebra em
        várias linhas (cada uma centralizada) em vez de estourar a coluna."""
        import textwrap
        partes = textwrap.wrap(texto, RECEIPT_WIDTH, break_long_words=True) or [""]
        return "\n".join(p.center(RECEIPT_WIDTH) for p in partes)

    def build_receipt_text(self, date_str, time_str, total_pedido):
        w = RECEIPT_WIDTH
        linhas = []
        linhas.append("=" * w)
        linhas.append(self._center(EMPRESA_NOME))
        linhas.append("=" * w)
        linhas.append(self._center(EMPRESA_RESPONSAVEL))
        linhas.append(self._center(f"CNPJ: {EMPRESA_CNPJ}"))
        linhas.append(self._center(EMPRESA_ENDERECO_1))
        linhas.append(self._center(EMPRESA_ENDERECO_2))
        linhas.append("=" * w)
        linhas.append(self._center(f"Data: {date_str}"))
        linhas.append(self._center(f"Hora: {time_str}"))
        linhas.append("-" * w)

        for nome, qtd in self.cart.items():
            preco = self.menu[nome]["preco"]
            sub = preco * qtd
            linhas.append(self._center(f"{qtd}x {nome}"))
            linhas.append(self._center(f"R$ {sub:.2f}"))
        linhas.append("-" * w)

        linhas.append(self._center("TOTAL A PAGAR"))
        linhas.append(self._center(f"R$ {total_pedido:.2f}"))
        linhas.append("=" * w)
        linhas.append(self._center("Obrigado pela preferência!"))
        linhas.append("=" * w)
        return "\n".join(linhas)

    def imprimir_conferencia(self):
        """Imprime o pedido da mesa atual SEM finalizar a venda (a mesa continua aberta)."""
        if not self.cart:
            messagebox.showwarning("Aviso", "O pedido está vazio.")
            return
        w, now = RECEIPT_WIDTH, datetime.now()
        total = sum(self.menu[n]["preco"] * q for n, q in self.cart.items())
        L = ["=" * w, self._center(EMPRESA_NOME), self._center(self.current_table.upper()),
             self._center("CONFERENCIA DO PEDIDO"), self._center(now.strftime("%d/%m/%Y %H:%M")), "-" * w]
        for nome, qtd in self.cart.items():
            L.append(self._center(f"{qtd}x {nome}"))
            L.append(self._center(f"R$ {self.menu[nome]['preco'] * qtd:.2f}"))
        L += ["-" * w, self._center("TOTAL"), self._center(f"R$ {total:.2f}"), "=" * w]
        cupons_dir = os.path.join(DATA_DIR, "cupons")
        filename = os.path.join(cupons_dir, f"Pedido_{now.strftime('%d%m%Y_%H%M%S')}.txt")
        try:
            os.makedirs(cupons_dir, exist_ok=True)
            with open(filename, "w", encoding="utf-8") as f:
                f.write("\n".join(L))
        except Exception as e:
            messagebox.showerror("Erro", f"Erro ao gerar o pedido: {e}")
            return
        sucesso, erro = self.print_receipt(filename)
        if not sucesso:
            messagebox.showwarning("Impressão", f"Não foi possível imprimir.\n\nDetalhe: {erro}")

    # --- ATUALIZAÇÃO AUTOMÁTICA ---
    def verificar_update(self, silencioso=False):
        if self._upd_ocupado:
            if not silencioso:
                messagebox.showinfo("Atualização", "Já existe uma verificação ou atualização em andamento. Aguarde um instante.")
            return
        self._upd_ocupado = True

        def tarefa():
            try:
                info = atualizador.checar(REPO_ATUALIZACAO, VERSAO)
            except Exception as e:
                msg = str(e)
                self.root.after(0, lambda: self._fim_check_erro(msg, silencioso))
                return
            self.root.after(0, lambda: self.pos_check(info, silencioso))
        threading.Thread(target=tarefa, daemon=True).start()

    def _fim_check_erro(self, msg, silencioso):
        self._upd_ocupado = False
        if not silencioso:
            messagebox.showerror("Atualização", f"Não foi possível verificar:\n{msg}")

    def pos_check(self, info, silencioso):
        if not info:
            self._upd_ocupado = False
            if not silencioso:
                messagebox.showinfo("Atualização", "Você já está na versão mais recente.")
            return
        if messagebox.askyesno("Atualização", f"Versão {info['versao']} disponível.\n"
                               "Atualizar agora? O programa vai reiniciar.\n(Pedidos abertos são mantidos.)"):
            threading.Thread(target=self.aplicar_update, args=(info,), daemon=True).start()  # fica ocupado até reiniciar
        else:
            self._upd_ocupado = False

    def aplicar_update(self, info):
        try:
            atualizador.trocar_exe(info)   # baixa, confere SHA-256, troca com backup e reabre
        except Exception as e:
            msg = str(e)
            def falhou():
                self._upd_ocupado = False
                messagebox.showerror("Atualização", f"Não foi possível atualizar:\n{msg}")
            self.root.after(0, falhou)
            return
        self.save_orders()  # garante que as comandas abertas estão em disco
        os._exit(0)

    def print_receipt(self, filepath):
        """Envia o cupom diretamente para a impressora padrão do sistema."""
        try:
            abs_path = os.path.abspath(filepath)
            if sys.platform.startswith("win"):
                os.startfile(abs_path, "print")
            elif sys.platform == "darwin":
                subprocess.run(["lpr", abs_path], check=True)
            else:
                subprocess.run(["lpr", abs_path], check=True)
            return True, None
        except Exception as e:
            return False, str(e)

